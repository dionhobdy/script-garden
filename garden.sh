# set the script directory path and store the discovered scripts in an array
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/scripts" && pwd)"
SCRIPTS=()

# exit the current child script and return to the main menu
return_to_garden() { 
    exit 0
}

export -f return_to_garden

# read user input while checking for ctrl+b
garden_read() {
    local prompt="$1"
    local input=""
    local char

    printf '%s' "$prompt"
    while IFS= read -r -n1 char; do
        # ctrl + b: return to Script Garden
        if [[ $char == $'\x02' ]]; then
            printf '\nreturning to script garden...\n'
            return_to_garden
        fi

        # enter: finish reading input
        if [[ -z "$char" ]]; then
            printf '\n'
            REPLY="$input"
            return 0
        fi

        #backspace: remove last character from input
        if [[ "$char" == $'\x7f' || "$char" == $'\b' ]]; then
            if [[ -n "$input" ]]; then
                input="${input%?}"
                printf '\b \b'
            fi
            continue
        fi

        # append and display the character
        input+="$char"
        printf '%s' "$char"

    done

    REPLY="$input"
}

# discover the scripts

discover_scripts() {
    SCRIPTS=()
    local file
    while IFS= read -r -d '' file; do
      # never list the master script itself
      [[ "$file" == "$SCRIPT_DIR/master.sh" ]] && continue
      SCRIPTS+=("$file")
      done < <(
        find "$SCRIPT_DIR" \
        -maxdepth 1 \
        -type f \
        -name '*.sh' \
        -print0 | sort -z
      )
}

# display the main menu
show_menu() {
  clear
  title_display
  echo #
  printf 'Directory: %s\n' "$SCRIPT_DIR"
  printf '\n'

  discover_scripts

  if ((${#SCRIPTS[@]} == 0)); then
    printf '%s\n' 'no scripts found.'
  else
    local i=1
    local file

    for file in "${SCRIPTS[@]}"; do
      printf ' %2d. %s\n' "$i" "$(basename "$file")"
      ((i++))
    done
  fi

  printf '\n'
  printf '%s\n' " 0. Exit"
  printf '\n'
  printf '%s\n' "ctrl+b: return to script garden"
  printf '\n'
}

# establish the script launcher
run_script() {
  local script="$1"

  if [[ ! -f "$script" ]]; then
    printf '\nno script found,\n'
    sleep 2
    return
  fi

  printf '\nlaunching script: %s\n' "$(basename "$script")"
  sleep 1

  # launch script in separate bash process
  bash "$script"

  local exit_code=$?

  printf '\n'
  printf 'script finished: %s\n' "$(basename "$script")"
  printf 'exit code: %s\n' "$exit_code"
  printf '\n'

  read -r -p 'press enter to return to script garden...'
}

# create a main loop to display the menu and listen for user input
main_loop() {
  local choice
  local selected_script

  while true; do
    show_menu
    read -r -p 'select a script (0 to exit): ' choice

    # exit script garden
    if [[ "$choice" == "0" ]]; then
      printf '\nexiting script garden...\n'
      break
    fi

    # validate the selection
    if [[ ! "$choice" =~ ^[0-9]+$ ]] || ((choice < 1 || choice > ${#SCRIPTS[@]})); then
      printf '\ninvalid selection, please try again.\n'
      sleep 1
      continue
    fi

    # retrieve the selected script
    selected_script="${SCRIPTS[$((choice - 1))]}"

    # launch the script
    run_script "$selected_script"

    done
}

# start script garden
main_loop